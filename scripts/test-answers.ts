import assert from 'node:assert/strict';
import fixture from '../fixtures/quote.clarifying.json';
import { applyAnswers } from '../lib/applyAnswers';
import type { QuoteRow } from '../lib/types';

const original = fixture as QuoteRow;
const partial = applyAnswers(original, 'record_answers', { quantity: 50 });
assert.deepEqual(partial.result.missing, ['materialGrade', 'finish']);
assert.equal(original.spec.quantity.value, null);
const complete = applyAnswers(partial.row, 'record_answers', { materialGrade: 'AL6061', finish: 'ANODIZE_CLEAR' });
assert.equal(complete.row.status, 'quoted');
assert.deepEqual(complete.row.options?.map(x => [x.totalCents, x.businessDays]), [[64485,18], [71650,13], [93145,8]]);
const corrected = applyAnswers(complete.row, 'record_answers', { quantity: 75 });
assert.equal(corrected.row.spec.quantity.value, 75);
assert.notDeepEqual(corrected.row.options, complete.row.options);
const unsupported = applyAnswers(corrected.row, 'note_unsupported', { field: 'materialGrade', heard: 'titanium' });
assert.equal(unsupported.row.spec.materialGrade.value, 'AL6061');
assert.equal(unsupported.result.rejected.length, 1);
assert.match(unsupported.row.spec.materialGrade.note!, /titanium/);
const stainless = applyAnswers(corrected.row, 'record_answers', { materialGrade: 'SS304' });
assert.deepEqual(stainless.result.missing, ['finish']);
assert.equal(stainless.row.options, null);
assert.equal(applyAnswers(stainless.row, 'record_answers', { finish: 'ANODIZE_BLACK' }).result.rejected.length, 1);
assert.equal(applyAnswers(stainless.row, 'record_answers', { finish: 'AS_MACHINED' }).row.status, 'quoted');
for (const quantity of [0, -1, 1.5, 5001, '75']) assert.equal(applyAnswers(original, 'record_answers', { quantity }).result.rejected.length, 1);
assert.throws(() => applyAnswers(original, 'record_answers', { lengthMm: 999 }));
assert.throws(() => applyAnswers(original, 'unknown_tool', {}));
const approved = { ...corrected.row, status: 'approved' as const, approved_at: new Date().toISOString() };
assert.equal(applyAnswers(approved, 'record_answers', { quantity: 100 }).row.approved_at, null);
console.log('PASS: partial answers, deterministic prices, corrections, unsupported materials, incompatible finishes, validation, approval invalidation.');
