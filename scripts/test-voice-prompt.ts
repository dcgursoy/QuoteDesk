import assert from 'node:assert/strict';
import fixture from '../fixtures/quote.clarifying.json';
import { buildInstruction } from '../lib/voicePrompt';
import type { QuoteRow } from '../lib/types';

const prompt = buildInstruction(fixture as QuoteRow);
assert.match(prompt, /Would a quick explanation of the material or finish options help/);
assert.match(prompt, /Do not repeat these offers every turn/);
assert.match(prompt, /pause data collection and explain/);
assert.match(prompt, /do not call note_unsupported just because they need an explanation/);
assert.match(prompt, /not a professional engineer or design adviser/);
assert.match(prompt, /Do not recommend, rank, or choose materials/);
assert.match(prompt, /You may neutrally explain terminology/);
assert.match(prompt, /help collect any other details they do know/);
assert.match(prompt, /a general "yes" to a list of options does not select one/);
assert.match(prompt, /Save the stated quantity 25 through record_answers/);
assert.match(prompt, /Never save an agent-selected default or an inferred engineering choice/);
assert.doesNotMatch(prompt, /You may recommend|I'd suggest|preliminary quoting starting point/);
assert.match(prompt, /Leave the field missing until they explicitly choose/);
assert.match(prompt, /6061 aluminum \(AL6061\)/);
assert.match(prompt, /note_price_request/);
assert.match(prompt, /Never calculate or invent prices yourself/);
console.log('PASS: neutral explanations, no engineering recommendations, explicit buyer choices, partial collection, existing price safeguards.');
